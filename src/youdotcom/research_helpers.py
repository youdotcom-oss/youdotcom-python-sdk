def research_and_wait(
    client: You,
    *,
    timeout_s: Optional[float] = None,
    **kwargs: Any,
) -> TaskDetail:
    """Submit a research task in background mode and wait for completion.

    Submits via :func:`research_background`, then opens the SSE stream
    and reads events until a terminal event arrives. Fetches the final
    ``TaskDetail`` via a ``get_research_task`` call (a second GET is
    issued in timeout/stream-close fallback paths).

    The stream is opened with a per-read timeout bounded to ``timeout_s``
    so that a stalled server raises ``httpx.ReadTimeout`` deterministically
    instead of leaking a blocked consumer thread. A total wall-clock deadline
    is also enforced.

    Parameters:
        timeout_s: Maximum seconds to wait for a terminal stream event.
            When ``None`` (the default), the timeout is auto-selected based
            on ``research_effort``: 600.0 (10 minutes) for standard/deep/
            exhaustive, 14400.0 (4 hours) for ``frontier``. Pass an explicit
            value to override.
        ``**kwargs``: Forwarded to ``client.research``, including
            ``input`` and ``research_effort``. ``background=True`` is set
            automatically. ``server_url``, ``timeout_ms``, and
            ``http_headers`` are forwarded to all sub-requests.

    Returns:
        ``TaskDetail`` with ``status == completed`` and the task's
        ``result`` attribute populated.

    Raises:
        TimeoutError: If no terminal event arrives within ``timeout_s``
            and the task is still non-terminal.
        RuntimeError: If the task ends in a non-completed terminal state.
    """
    if timeout_s is None:
        timeout_s = _resolve_default_timeout(kwargs)
    server_url = kwargs.get("server_url")
    timeout_ms = kwargs.get("timeout_ms")
    http_headers = kwargs.get("http_headers")
    task = research_background(client, **kwargs)

    # The SSE per-read timeout is bounded to timeout_s so a silent stall
    # can never exceed the total wait budget. This is decoupled from the
    # caller's timeout_ms (which governs individual HTTP requests like the
    # POST and GET, not SSE event gaps).
    stream_timeout_ms = int(timeout_s * 1000)
    try:
        stream = _open_raw_stream(
            client, task.task_id, http_headers=http_headers,
            server_url=server_url, timeout_ms=stream_timeout_ms,
        )
    except httpx.TransportError:
        # Transient connection failure (can't reach server, etc.): the task
        # is already submitted. Fall back to polling. Typed errors (401/403/
        # 404/500 from _raise_stream_error) propagate to the caller.
        return poll_research_task(
            client, task.task_id,
            interval_s=_DEFAULT_POLL_INTERVAL_S,
            timeout_s=timeout_s,
            server_url=server_url, timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
    result: Optional[str] = None
    timed_out = False
    deadline = time.monotonic() + timeout_s
    try:
        for evt in stream:
            if evt.event in _TERMINAL_STREAM_EVENTS_OK:
                result = "ok"
                break
            if evt.event in _TERMINAL_STREAM_EVENTS_ERR:
                result = evt.event
                break
            if time.monotonic() >= deadline:
                timed_out = True
                break
    except httpx.TimeoutException:
        timed_out = True
    except httpx.TransportError:
        # Mid-stream network failure (e.g. RemoteProtocolError on a dropped
        # connection): the task is already submitted and running. Fall back
        # to polling. Typed SDK errors propagate to the caller.
        stream.close()
        return poll_research_task(
            client, task.task_id,
            interval_s=_DEFAULT_POLL_INTERVAL_S,
            timeout_s=timeout_s,
            server_url=server_url, timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
    finally:
        stream.close()

    return _resolve_from_final_get(
        client, task.task_id, result, timeout_s,
        server_url=server_url, timeout_ms=timeout_ms, http_headers=http_headers,
        timed_out=timed_out,
    )


async def research_and_wait_async(
    client: You,
    *,
    timeout_s: Optional[float] = None,
    **kwargs: Any,
) -> TaskDetail:
    """Async variant of :func:`research_and_wait`.

    See :func:`research_and_wait` for parameter details and auto-timeout
    behavior (600s default, 14400s for frontier). The SSE per-read timeout
    is bounded to ``timeout_s``, matching the sync variant.
    """
    if timeout_s is None:
        timeout_s = _resolve_default_timeout(kwargs)
    server_url = kwargs.get("server_url")
    timeout_ms = kwargs.get("timeout_ms")
    http_headers = kwargs.get("http_headers")
    task = await research_background_async(client, **kwargs)

    # The SSE per-read timeout is bounded to timeout_s (same rationale as
    # sync). Decoupled from the caller's timeout_ms, which governs
    # individual HTTP requests (POST, GET), not SSE event gaps.
    stream_timeout_ms = int(timeout_s * 1000)

    async def _consume() -> Optional[str]:
        async for evt in stream_research_async(
            client, task.task_id,
            server_url=server_url, timeout_ms=stream_timeout_ms,
            http_headers=http_headers,
        ):
            if evt.event in _TERMINAL_STREAM_EVENTS_OK:
                return "ok"
            if evt.event in _TERMINAL_STREAM_EVENTS_ERR:
                return evt.event
        return None

    timed_out = False
    try:
        result = await asyncio.wait_for(_consume(), timeout=timeout_s)
    except (asyncio.TimeoutError, httpx.TimeoutException):
        timed_out = True
        result = None
    except httpx.TransportError:
        # Transient connection failure (can't reach server, dropped
        # connection, etc.): the task is already submitted. Fall back to
        # polling. Typed errors (401/403/404/500) propagate to the caller.
        return await poll_research_task_async(
            client, task.task_id,
            interval_s=_DEFAULT_POLL_INTERVAL_S,
            timeout_s=timeout_s,
            server_url=server_url, timeout_ms=timeout_ms,
            http_headers=http_headers,
        )

    return await _resolve_from_final_get_async(
        client, task.task_id, result, timeout_s,
        server_url=server_url, timeout_ms=timeout_ms, http_headers=http_headers,
        timed_out=timed_out,
    )


def _raise_stream_error(http_res: Any) -> None:
    """Raise the typed ``StreamResearchTask*Error`` for non-200 responses.

    Mirrors the error-handling branches in the generated
    ``client.stream_research_task`` so that callers of ``stream_research``
    get the same structured exceptions (401/403/404/500) as the generated
    method instead of a generic ``RuntimeError``.
    """
    response_data: Any = None
    for status, content_type, data_cls, err_cls in _STREAM_ERROR_BRANCHES:
        if match_response(http_res, status, content_type):
            text = stream_to_text(http_res)
            response_data = unmarshal_json_response(data_cls, http_res, text)
            raise err_cls(response_data, http_res, text)
    if match_response(http_res, "4XX", "*") or match_response(http_res, "5XX", "*"):
        text = stream_to_text(http_res)
        raise _errors.YouDefaultError("API error occurred", http_res, text)
    text = stream_to_text(http_res)
    raise _errors.YouDefaultError("Unexpected response received", http_res, text)


async def _raise_stream_error_async(http_res: Any) -> None:
    """Async counterpart of :func:`_raise_stream_error`."""
    response_data: Any = None
    for status, content_type, data_cls, err_cls in _STREAM_ERROR_BRANCHES:
        if match_response(http_res, status, content_type):
            text = await stream_to_text_async(http_res)
            response_data = unmarshal_json_response(data_cls, http_res, text)
            raise err_cls(response_data, http_res, text)
    if match_response(http_res, "4XX", "*") or match_response(http_res, "5XX", "*"):
        text = await stream_to_text_async(http_res)
        raise _errors.YouDefaultError("API error occurred", http_res, text)
    text = await stream_to_text_async(http_res)
    raise _errors.YouDefaultError("Unexpected response received", http_res, text)


def _stream_build_kwargs(
    client: You,
    task_id: str,
    *,
    http_headers: Optional[Mapping[str, str]],
    from_id: int,
    server_url: Optional[str],
    timeout_ms: Optional[int],
) -> dict[str, Any]:
    """Build common kwargs dict for ``_build_request[_async]``."""
    # pylint: disable=protected-access
    base_url = server_url if server_url is not None else client._get_url(None, None)
    if timeout_ms is None:
        timeout_ms = client.sdk_configuration.timeout_ms
    return {
        "method": "GET",
        "path": "/v1/research/{task_id}/stream",
        "base_url": base_url,
        "url_variables": None,
        "request": _models.StreamResearchTaskRequest(task_id=task_id, from_id=from_id),
        "request_body_required": False,
        "request_has_path_params": True,
        "request_has_query_params": True,
        "user_agent_header": "user-agent",
        "accept_header_value": "text/event-stream",
        "http_headers": http_headers,
        "security": client.sdk_configuration.security,
        "allow_empty_value": None,
        "timeout_ms": timeout_ms,
    }


def _stream_hook_ctx(client: You, base_url: str) -> HookContext:
    """Build the shared ``HookContext`` for stream-open requests."""
    return HookContext(
        config=client.sdk_configuration,
        base_url=base_url or "",
        operation_id="streamResearchTask",
        oauth2_scopes=None,
        security_source=get_security_from_env(
            client.sdk_configuration.security, _models.Security
        ),
        tags=None,
        extensions=None,
    )


def _open_raw_stream(
    client: You,
    task_id: str,
    *,
    http_headers: Optional[Mapping[str, str]],
    from_id: int = 0,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
) -> eventstreaming.EventStream[RawStreamEvent]:
    """Issue the SSE request directly so we can pass a tolerant decoder.

    Mirrors the request setup used by ``client.stream_research_task`` but
    wires :func:`_decode_raw_event` into the ``EventStream`` instead of the
    strict pydantic ``ResearchTaskStreamEvent`` decoder.
    """
    kwargs = _stream_build_kwargs(
        client, task_id, http_headers=http_headers, from_id=from_id,
        server_url=server_url, timeout_ms=timeout_ms,
    )
    base_url = kwargs["base_url"]
    # pylint: disable=protected-access
    req = client._build_request(**kwargs)
    http_res = client.do_request(
        hook_ctx=_stream_hook_ctx(client, base_url),
        request=req,
        is_error_status_code=lambda c: match_status_codes(["4XX", "5XX"], c),
        stream=True,
        # Diverges from generated stream_research_task which retries
        # [429,500,502,503,504] on stream-open. We skip retries so a
        # transient 5xx doesn't silently reopen a half-consumed stream.
        retry_config=None,
    )
    if not match_response(http_res, "200", "text/event-stream"):
        _raise_stream_error(http_res)
    return eventstreaming.EventStream(
        http_res,
        _decode_raw_event,
        client_ref=client,
        data_required=False,
    )


def stream_research(
    client: You,
    task_id: str,
    *,
    http_headers: Optional[Mapping[str, str]] = None,
    from_id: int = 0,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
) -> Iterator[RawStreamEvent]:
    """SSE iterator that accepts unknown event names without failing.

    Each yielded item is a :class:`RawStreamEvent` carrying the raw ``event``
    string and parsed JSON ``data`` payload. Useful when the server may emit
    intermediate workflow events with names outside the documented enum
    (e.g. ``research.searching``, ``response.created``,
    ``response.output_item.added``).

    Parameters:
        from_id: Sequence number to resume from (reconnection). ``0`` starts at
            the beginning of the stream.
    """
    with _open_raw_stream(
        client, task_id, http_headers=http_headers, from_id=from_id,
        server_url=server_url, timeout_ms=timeout_ms,
    ) as stream:
        yield from stream


