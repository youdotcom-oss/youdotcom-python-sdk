def research_and_wait(
    client: You,
    *,
    mode: str = "poll",
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
    **kwargs: Any,
) -> TaskDetail:
    """Submit a research task in background mode and wait for completion.

    Parameters:
        mode: ``"poll"`` (default) or ``"stream"``. Both modes submit a
            background task and wait for completion, returning the final
            ``TaskDetail``. ``"poll"`` polls ``GET /v1/research/{task_id}``
            at ``interval_s`` intervals. ``"stream"`` opens the SSE stream
            (``GET /v1/research/{task_id}/stream``) and reads events until
            a terminal event arrives, then fetches the final ``TaskDetail``.
            If the stream doesn't deliver a terminal event within
            45 seconds, the stream is closed and polling takes over,
            no concurrent polling traffic during the stream phase.
        interval_s: Poll interval in seconds.
        timeout_s: Maximum seconds to wait for completion.
        ``**kwargs``: Forwarded to ``client.research``, including
            ``input`` and ``research_effort``. ``background=True`` is set
            automatically.

    Returns:
        ``TaskDetail`` with ``status == completed`` and the task's
        ``result`` attribute populated. The ``Result`` model uses
        ``extra="allow"``, so ``detail.result.model_dump()`` returns
        the full ``ResearchResponse`` payload dict. For a typed
        ``ResearchResponse`` object (with ``output.content`` as a
        ``str`` for text responses), issue a follow-up synchronous
        ``client.research(..., background=False)`` call with the same
        ``input`` and ``research_effort``.
    """
    if mode not in {"poll", "stream"}:
        raise ValueError(f"mode must be 'poll' or 'stream', got {mode!r}")
    # Extract per-call overrides that apply to ALL sub-requests (submit,
    # poll, stream), not just the initial research() call.
    server_url = kwargs.get("server_url")
    timeout_ms = kwargs.get("timeout_ms")
    http_headers = kwargs.get("http_headers")
    task = research_background(client, **kwargs)
    if mode == "poll":
        return poll_research_task(
            client,
            task.task_id,
            interval_s=interval_s,
            timeout_s=timeout_s,
            server_url=server_url,
            timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
    deadline = time.monotonic() + timeout_s
    # Stream mode: try the SSE stream first. If it delivers a terminal
    # event within the fallback window, fetch the final TaskDetail. If not,
    # close the stream and fall back to polling. This avoids concurrent
    # polling traffic. The caller chose "stream", so we use the stream,
    # and only poll as a sequential fallback.
    try:
        stream = _open_raw_stream(
            client, task.task_id, http_headers=http_headers,
            server_url=server_url, timeout_ms=timeout_ms,
        )
    except Exception:  # pylint: disable=broad-except
        # Stream open failed (404, 500, connection error, etc.).
        # The task was already submitted, so fall back to polling
        # instead of orphaning it.
        stream = None

    if stream is not None:
        try:
            box: dict[str, Any] = {}

            def _stream_worker() -> None:
                try:
                    for evt in stream:
                        name = evt.event
                        if name in _TERMINAL_STREAM_EVENTS_OK:
                            box["ok"] = True
                            return
                        if name in _TERMINAL_STREAM_EVENTS_ERR:
                            box["err"] = name
                            return
                except Exception:  # pylint: disable=broad-except
                    pass  # stream closed or errored, fall back to polling

            stream_thread = threading.Thread(target=_stream_worker, daemon=True)
            stream_thread.start()

            stream_timeout = min(timeout_s, _STREAM_FALLBACK_TIMEOUT_S)
            stream_thread.join(timeout=stream_timeout)

            # Close the stream to unblock the worker if it's still running.
            stream.close()
            stream_thread.join(timeout=2.0)

            if "ok" in box:
                # Stream detected a terminal event, fetch the final TaskDetail.
                return poll_research_task(
                    client,
                    task.task_id,
                    interval_s=interval_s,
                    timeout_s=max(interval_s, deadline - time.monotonic()),
                    server_url=server_url,
                    timeout_ms=timeout_ms,
                    http_headers=http_headers,
                )
            if "err" in box:
                raise RuntimeError(
                    f"research task {task.task_id} ended in non-completed state: {box['err']}"
                )
        finally:
            stream.close()

    # Stream didn't deliver a terminal event within the fallback window.
    # Fall back to polling with the remaining time.
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise TimeoutError(
            f"research task {task.task_id} did not complete within {timeout_s}s"
        )
    return poll_research_task(
        client,
        task.task_id,
        interval_s=interval_s,
        timeout_s=remaining,
        server_url=server_url,
        timeout_ms=timeout_ms,
        http_headers=http_headers,
    )


async def research_and_wait_async(
    client: You,
    *,
    mode: str = "poll",
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
    **kwargs: Any,
) -> TaskDetail:
    """Async variant of :func:`research_and_wait`."""
    if mode not in {"poll", "stream"}:
        raise ValueError(f"mode must be 'poll' or 'stream', got {mode!r}")
    # Extract per-call overrides that apply to ALL sub-requests.
    server_url = kwargs.get("server_url")
    timeout_ms = kwargs.get("timeout_ms")
    http_headers = kwargs.get("http_headers")
    task = await research_background_async(client, **kwargs)
    if mode == "poll":
        return await poll_research_task_async(
            client,
            task.task_id,
            interval_s=interval_s,
            timeout_s=timeout_s,
            server_url=server_url,
            timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
    deadline = time.monotonic() + timeout_s
    # Stream mode: same rationale as the sync version. Try the SSE stream
    # first, fall back to polling if no terminal event within the fallback
    # window. No concurrent polling, the caller chose "stream".
    stream_timeout = min(timeout_s, _STREAM_FALLBACK_TIMEOUT_S)

    async def _stream_consumer() -> Optional[str]:
        async with contextlib.aclosing(
            stream_research_events_raw_async(  # type: ignore[type-var]
                client, task.task_id,
                server_url=server_url, timeout_ms=timeout_ms,
                http_headers=http_headers,
            )
        ) as agen:
            async for evt in agen:
                name = evt.event
                if name in _TERMINAL_STREAM_EVENTS_OK:
                    return "ok"
                if name in _TERMINAL_STREAM_EVENTS_ERR:
                    return name
        return None

    try:
        stream_result = await asyncio.wait_for(
            _stream_consumer(), timeout=stream_timeout
        )
    except Exception:  # pylint: disable=broad-except
        # Timeout: stream didn't deliver a terminal event in time.
        # Or stream open/connection failed.
        # In either case, fall back to polling.
        stream_result = None

    if stream_result == "ok":
        return await poll_research_task_async(
            client,
            task.task_id,
            interval_s=interval_s,
            timeout_s=max(interval_s, deadline - time.monotonic()),
            server_url=server_url,
            timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
    if stream_result is not None:
        raise RuntimeError(
            f"research task {task.task_id} ended in non-completed state: {stream_result}"
        )

    # Stream didn't deliver a terminal event, fall back to polling.
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise TimeoutError(
            f"research task {task.task_id} did not complete within {timeout_s}s"
        )
    return await poll_research_task_async(
        client,
        task.task_id,
        interval_s=interval_s,
        timeout_s=remaining,
        server_url=server_url,
        timeout_ms=timeout_ms,
        http_headers=http_headers,
    )


def _open_raw_stream(
    client: You,
    task_id: str,
    *,
    http_headers: Optional[Mapping[str, str]],
    from_id: int = 0,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
) -> eventstreaming.EventStream[RawStreamEvent]:
    """Issue the SSE request directly so we can pass a tolerant decoder.

    Mirrors the request setup used by ``client.stream_research_task`` but
    wires :func:`_decode_raw_event` into the ``EventStream`` instead of the
    strict pydantic ``ResearchTaskStreamEvent`` decoder.
    """
    # pylint: disable=protected-access
    base_url = server_url if server_url is not None else client._get_url(None, None)
    if timeout_ms is None:
        timeout_ms = client.sdk_configuration.timeout_ms
    req = client._build_request(
        method="GET",
        path="/v1/research/{task_id}/stream",
        base_url=base_url,
        url_variables=None,
        request=_models.StreamResearchTaskRequest(task_id=task_id, from_id=from_id),
        request_body_required=False,
        request_has_path_params=True,
        request_has_query_params=True,
        user_agent_header="user-agent",
        accept_header_value="text/event-stream",
        http_headers=http_headers,
        security=client.sdk_configuration.security,
        allow_empty_value=None,
        timeout_ms=timeout_ms,
    )
    http_res = client.do_request(
        hook_ctx=HookContext(
            config=client.sdk_configuration,
            base_url=base_url or "",
            operation_id="streamResearchTask",
            oauth2_scopes=None,
            security_source=get_security_from_env(
                client.sdk_configuration.security, _models.Security
            ),
            tags=None,
            extensions=None,
        ),
        request=req,
        is_error_status_code=lambda c: match_status_codes(["4XX", "5XX"], c),
        stream=True,
        retry_config=None,
    )
    if not match_response(http_res, "200", "text/event-stream"):
        http_res.close()
        raise RuntimeError(
            f"unexpected response from research stream: {http_res.status_code}"
        )
    return eventstreaming.EventStream(
        http_res,
        _decode_raw_event,
        client_ref=client,
        data_required=False,
    )


def stream_research_events_raw(
    client: You,
    task_id: str,
    *,
    http_headers: Optional[Mapping[str, str]] = None,
    from_id: int = 0,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
) -> Iterator[RawStreamEvent]:
    """SSE iterator that accepts unknown event names without failing.

    Each yielded item is a :class:`RawStreamEvent` carrying the raw ``event``
    string and parsed JSON ``data`` payload. Useful when the server may emit
    intermediate workflow events with names outside the documented enum
    (``connected``/``response.done``/``complete``/``error``/``cancelled``).

    Parameters:
        from_id: Sequence number to resume from (reconnection). ``0`` starts at
            the beginning of the stream.
    """
    # pylint: disable-next=protected-access
    with _open_raw_stream(
        client, task_id, http_headers=http_headers, from_id=from_id,
        server_url=server_url, timeout_ms=timeout_ms,
    ) as stream:
        yield from stream


