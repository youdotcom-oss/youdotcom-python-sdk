"""Hand-maintained research workflow helpers.

This module is NOT regenerated by Speakeasy. It adds convenience helpers on
top of the auto-generated research endpoints:

- ``research_background`` / ``research_background_async``: Submit a research
  task with ``background=True`` and return the ``TaskResponse`` directly so
  callers don't need to narrow the ``Union[ResearchResponse, TaskResponse]``
  response shape.
- ``poll_research_task`` / ``poll_research_task_async``: Poll
  ``GET /v1/research/{task_id}`` until the task reaches a terminal state
  (``completed``, ``failed``, ``cancelled``).
- ``research_and_wait`` / ``research_and_wait_async``: Submit a research task
  with ``background=True``, then either poll or stream until completion and
  return the final ``TaskDetail``.
- ``stream_research_events_raw`` / ``stream_research_events_raw_async``:
  Iterate the SSE event stream with a tolerant decoder that surfaces
  non-typed event names (``research.searching``, etc.) as raw dicts instead
  of crashing on validation. Use this when the server may emit event types
  outside the documented ``connected``/``response.done``/``complete``/
  ``error``/``cancelled`` set.
"""

from __future__ import annotations

import asyncio
import json
import time
from dataclasses import dataclass
from typing import Any, AsyncIterator, Iterator, Mapping, Optional

import youdotcom.models as _models
from youdotcom._hooks.types import HookContext
from youdotcom.sdk import You
from youdotcom.models import TaskDetail, TaskResponse
from youdotcom.utils import eventstreaming, get_security_from_env, match_response, match_status_codes


_DEFAULT_POLL_INTERVAL_S = 2.0
_DEFAULT_POLL_TIMEOUT_S = 600.0
_TERMINAL_TASK_STATUSES = frozenset({"completed", "failed", "cancelled"})


@dataclass
class RawStreamEvent:
    """Tolerant SSE event representation.

    Attributes:
        id: SSE event ID (``id:`` directive) when supplied.
        event: Raw event name as received from the server, NOT validated
            against the documented enum.
        data: Parsed JSON payload when the data line is valid JSON,
            otherwise the raw string.
        retry: Optional ``retry:`` directive from the server, if any.
    """

    id: Optional[str]
    event: Optional[str]
    data: Any
    retry: Optional[int]


def _decode_raw_event(raw_json: str) -> RawStreamEvent:
    """Tolerant SSE decoder used by ``stream_research_events_raw``.

    Accepts any JSON object regardless of whether ``event`` matches the
    documented enum, so unknown workflow events pass through instead of
    failing pydantic validation.
    """
    parsed = json.loads(raw_json)
    if not isinstance(parsed, dict):
        return RawStreamEvent(id=None, event=None, data=parsed, retry=None)
    return RawStreamEvent(
        id=parsed.get("id"),
        event=parsed.get("event"),
        data=parsed.get("data"),
        retry=parsed.get("retry"),
    )


def research_background(client: You, **kwargs: Any) -> TaskResponse:
    """Submit a research task with ``background=True`` and return ``TaskResponse``.

    Equivalent to ``client.research(..., background=True)`` but asserts the
    response is a ``TaskResponse`` so callers get a strong return type
    without needing to narrow ``Union[ResearchResponse, TaskResponse]``.
    """
    kw = dict(kwargs)
    kw["background"] = True
    res = client.research(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background requires background=True so the server "
            "returns TaskResponse; got " + type(res).__name__
        )
    return res


async def research_background_async(client: You, **kwargs: Any) -> TaskResponse:
    """Async variant of :func:`research_background`."""
    kw = dict(kwargs)
    kw["background"] = True
    res = await client.research_async(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background_async requires background=True so the "
            "server returns TaskResponse; got " + type(res).__name__
        )
    return res


def _poll_detail(
    client: You,
    *,
    task_id: str,
    interval_s: float,
    timeout_s: float,
    deadline: float,
) -> TaskDetail:
    while True:
        detail = client.get_research_task(task_id=task_id)
        status = getattr(detail.status, "value", detail.status)
        if status in _TERMINAL_TASK_STATUSES:
            if status != "completed":
                raise RuntimeError(
                    f"research task {task_id} ended in non-completed state: {status}"
                )
            return detail
        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"research task {task_id} did not complete within {timeout_s}s"
            )
        time.sleep(interval_s)


def poll_research_task(
    client: You,
    task_id: str,
    *,
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
) -> TaskDetail:
    """Poll ``GET /v1/research/{task_id}`` until ``status == "completed"``.

    Raises ``RuntimeError`` if the task ends in a non-completed terminal state
    (``failed`` / ``cancelled``) and ``TimeoutError`` if ``timeout_s`` elapses
    before completion.
    """
    return _poll_detail(
        client,
        task_id=task_id,
        interval_s=interval_s,
        timeout_s=timeout_s,
        deadline=time.monotonic() + timeout_s,
    )


async def _poll_detail_async(
    client: You,
    *,
    task_id: str,
    interval_s: float,
    timeout_s: float,
    deadline: float,
) -> TaskDetail:
    while True:
        detail = await client.get_research_task_async(task_id=task_id)
        status = getattr(detail.status, "value", detail.status)
        if status in _TERMINAL_TASK_STATUSES:
            if status != "completed":
                raise RuntimeError(
                    f"research task {task_id} ended in non-completed state: {status}"
                )
            return detail
        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"research task {task_id} did not complete within {timeout_s}s"
            )
        await asyncio.sleep(interval_s)


async def poll_research_task_async(
    client: You,
    task_id: str,
    *,
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
) -> TaskDetail:
    """Async variant of :func:`poll_research_task`."""
    return await _poll_detail_async(
        client,
        task_id=task_id,
        interval_s=interval_s,
        timeout_s=timeout_s,
        deadline=time.monotonic() + timeout_s,
    )


def research_and_wait(
    client: You,
    *,
    mode: str = "poll",
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
    **kwargs: Any,
) -> TaskDetail:
    """Submit a research task in background mode and wait for completion.

    Parameters:
        mode: ``"poll"`` (default) or ``"stream"``. ``stream`` reads the SSE
            stream until a terminal ``response.done`` event arrives, then
            fetches the final ``TaskDetail`` for the structured payload.
        interval_s: Poll interval in seconds (poll mode only).
        timeout_s: Maximum seconds to wait for completion.
        ``**kwargs``: Forwarded to ``client.research``, including
            ``input`` and ``research_effort``. ``background=True`` is set
            automatically.

    Returns:
        ``TaskDetail`` with ``status == completed`` and the task's
        ``result`` attribute populated. Note: due to current SDK
        unmarshaling (``extra=ignore`` on the generic ``Result`` model
        which declares no fields), the inline ``ResearchResponse``
        payload in ``detail.result`` is not typed today —
        ``detail.result.model_dump()`` returns an empty dict because
        pydantic drops the unknown ``output`` keys. For text responses,
        the supported workaround is to issue a follow-up synchronous
        ``client.research(..., background=False)`` call with the same
        ``input`` and ``research_effort`` to get a typed
        ``ResearchResponse`` with ``output.content`` as a ``str``.
        Note: if the original task used ``output_schema`` for structured
        output, the sync fallback also returns an empty ``Content()``
        — there is no SDK-level workaround for structured output in
        2.4.0 (see ``overlays/python_overlay.yaml`` for the staged fix).
    """
    if mode not in {"poll", "stream"}:
        raise ValueError(f"mode must be 'poll' or 'stream', got {mode!r}")
    task = research_background(client, **kwargs)
    if mode == "poll":
        return poll_research_task(
            client,
            task.task_id,
            interval_s=interval_s,
            timeout_s=timeout_s,
        )
    deadline = time.monotonic() + timeout_s
    # Stream mode: poll until terminal event OR deadline, then fetch the
    # final detail. The deadline check below runs after each received event;
    # if the SSE connection itself stalls (server sends nothing), the real
    # backstop is the httpx read timeout on the underlying request, not
    # ``timeout_s``.
    for evt in stream_research_events_raw(client, task.task_id):
        name = evt.event
        if name in {"response.done", "complete"}:
            return poll_research_task(
                client,
                task.task_id,
                interval_s=interval_s,
                timeout_s=max(interval_s, deadline - time.monotonic()),
            )
        if name in {"error", "cancelled"}:
            raise RuntimeError(
                f"research task {task.task_id} ended in non-completed state: {name}"
            )
        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"research task {task.task_id} did not complete within {timeout_s}s"
            )
    # Stream ended without a terminal event; fall back to polling.
    return poll_research_task(
        client,
        task.task_id,
        interval_s=interval_s,
        timeout_s=max(interval_s, deadline - time.monotonic()),
    )


