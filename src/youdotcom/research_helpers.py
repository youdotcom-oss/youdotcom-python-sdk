_DEFAULT_POLL_INTERVAL_S = 2.0
_DEFAULT_POLL_TIMEOUT_S = 600.0
_FRONTIER_TIMEOUT_S = 14400.0  # 4 hours — frontier tasks can run this long
_REPOLL_MAX_ATTEMPTS = 3  # bounded re-poll on completion race (stream OK but GET not yet completed)
_REPOLL_INTERVAL_S = 1.0
_TERMINAL_TASK_STATUSES = frozenset({"completed", "failed", "cancelled"})
_TERMINAL_STREAM_EVENTS_OK = frozenset({"response.done", "complete", "completed"})
_TERMINAL_STREAM_EVENTS_ERR = frozenset({"error", "failed", "cancelled"})


def _resolve_default_timeout(kwargs: Mapping[str, Any]) -> float:
    """Pick a sensible default ``timeout_s`` based on ``research_effort``.

    Frontier tasks can run up to 4 hours; all other effort tiers complete
    well within the standard 10-minute default. Only called when the caller
    did not explicitly pass ``timeout_s``.
    """
    effort = kwargs.get("research_effort")
    if effort is not None:
        effort_val = effort.value if hasattr(effort, "value") else str(effort)
        if effort_val == "frontier":
            return _FRONTIER_TIMEOUT_S
    return _DEFAULT_POLL_TIMEOUT_S

# Typed-error branches for stream open: (status, content_type, DataClass, ErrorClass).
# Mirrors the generated stream_research_task error handling so callers of
# stream_research get the same structured exceptions as the generated method.
_STREAM_ERROR_BRANCHES = (
    ("401", "application/json", _errors.StreamResearchTaskUnauthorizedErrorData, _errors.StreamResearchTaskUnauthorizedError),
    ("403", "application/json", _errors.StreamResearchTaskForbiddenErrorData, _errors.StreamResearchTaskForbiddenError),
    ("404", "application/json", _errors.StreamResearchTaskNotFoundErrorData, _errors.StreamResearchTaskNotFoundError),
    ("500", "application/json", _errors.StreamResearchTaskInternalServerErrorData, _errors.StreamResearchTaskInternalServerError),
)


@dataclass
class RawStreamEvent:
    """Tolerant SSE event representation.

    Attributes:
        id: SSE event ID (``id:`` directive) when supplied.
        event: Raw event name as received from the server, NOT validated
            against the documented enum.
        data: Parsed JSON payload when the data line is valid JSON,
            otherwise the raw string.
    """

    id: Optional[str]
    event: Optional[str]
    data: Any


def _decode_raw_event(raw_json: str) -> RawStreamEvent:
    """Tolerant SSE decoder used by ``stream_research``.

    Accepts any JSON object regardless of whether ``event`` matches the
    documented enum, so unknown workflow events pass through instead of
    failing pydantic validation.
    """
    parsed = json.loads(raw_json)
    if not isinstance(parsed, dict):
        return RawStreamEvent(id=None, event=None, data=parsed)
    return RawStreamEvent(
        id=parsed.get("id"),
        event=parsed.get("event"),
        data=parsed.get("data"),
    )


def research_background(client: You, **kwargs: Any) -> TaskResponse:
    """Submit a research task with ``background=True`` and return ``TaskResponse``.

    Equivalent to ``client.research(..., background=True)`` but asserts the
    response is a ``TaskResponse`` so callers get a strong return type
    without needing to narrow ``Union[ResearchResponse, TaskResponse]``.
    """
    kw = dict(kwargs)
    kw["background"] = True
    res = client.research(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background requires background=True so the server "
            "returns TaskResponse; got " + type(res).__name__
        )
    return res


async def research_background_async(client: You, **kwargs: Any) -> TaskResponse:
    """Async variant of :func:`research_background`."""
    kw = dict(kwargs)
    kw["background"] = True
    res = await client.research_async(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background_async requires background=True so the "
            "server returns TaskResponse; got " + type(res).__name__
        )
    return res


def poll_research_task(
    client: You,
    task_id: str,
    *,
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
    http_headers: Optional[Mapping[str, str]] = None,
) -> TaskDetail:
    """Poll ``GET /v1/research/{task_id}`` until ``status == "completed"``.

    Parameters:
        interval_s: Seconds between poll requests. Defaults to 2.0.
        timeout_s: Maximum seconds to wait before raising ``TimeoutError``.
            Defaults to 600.0 (10 minutes). For ``frontier`` tasks (up to 4
            hours), pass ``timeout_s=14400``.

    Raises ``RuntimeError`` if the task ends in a non-completed terminal state
    (``failed`` / ``cancelled``) and ``TimeoutError`` if ``timeout_s`` elapses
    before completion.
    """
    deadline = time.monotonic() + timeout_s
    while True:
        detail = client.get_research_task(
            task_id=task_id,
            server_url=server_url,
            timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
        status = detail.status.value
        if status in _TERMINAL_TASK_STATUSES:
            if status != "completed":
                raise RuntimeError(
                    f"research task {task_id} ended in non-completed state: {status}"
                )
            return detail
        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"research task {task_id} did not complete within {timeout_s}s"
            )
        time.sleep(interval_s)


