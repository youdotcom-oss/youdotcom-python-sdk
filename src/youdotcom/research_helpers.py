"""Hand-maintained research workflow helpers.

This module is NOT regenerated by Speakeasy. It adds convenience helpers on
top of the auto-generated research endpoints:

- ``research_background`` / ``research_background_async``: Submit a research
  task with ``background=True`` and return the ``TaskResponse`` directly so
  callers don't need to narrow the ``Union[ResearchResponse, TaskResponse]``
  response shape.
- ``poll_research_task`` / ``poll_research_task_async``: Poll
  ``GET /v1/research/{task_id}`` until the task reaches a terminal state
  (``completed``, ``failed``, ``cancelled``).
- ``research_and_wait`` / ``research_and_wait_async``: Submit a research task
  with ``background=True``, then stream SSE events until a terminal event
  arrives, and fetch the final ``TaskDetail``.
- ``stream_research`` / ``stream_research_async``: Iterate the SSE event
  stream with a tolerant decoder that surfaces non-typed event names
  (``research.searching``, etc.) as raw dicts instead of crashing on
  validation. Use this when the server may emit event types outside the
  documented enum.
"""

