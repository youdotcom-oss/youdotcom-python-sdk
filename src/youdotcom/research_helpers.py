"""Hand-maintained research workflow helpers.

This module is NOT regenerated by Speakeasy. It adds convenience helpers on
top of the auto-generated research endpoints:

- ``research_background`` / ``research_background_async``: Submit a research
  task with ``background=True`` and return the ``TaskResponse`` directly so
  callers don't need to narrow the ``Union[ResearchResponse, TaskResponse]``
  response shape.
- ``poll_research_task`` / ``poll_research_task_async``: Poll
  ``GET /v1/research/{task_id}`` until the task reaches a terminal state
  (``completed``, ``failed``, ``cancelled``).
- ``research_and_wait`` / ``research_and_wait_async``: Submit a research task
  with ``background=True``, then wait for completion and return the final
  ``TaskDetail``. ``mode="poll"`` polls at regular intervals; ``mode="stream"``
  opens the SSE stream for real-time event detection and falls back to
  polling only if the stream doesn't deliver a terminal event within
  45 seconds (sequential, not concurrent).
- ``stream_research_events_raw`` / ``stream_research_events_raw_async``:
  Iterate the SSE event stream with a tolerant decoder that surfaces
  non-typed event names (``research.searching``, etc.) as raw dicts instead
  of crashing on validation. Use this when the server may emit event types
  outside the documented enum (``connected``, ``response.done``, ``complete``,
  ``error``, ``cancelled``) or additional event names (``completed``,
  ``failed``).
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import threading
import time
from dataclasses import dataclass
from typing import Any, AsyncIterator, Iterator, Mapping, Optional

import youdotcom.models as _models
from youdotcom._hooks.types import HookContext
from youdotcom.sdk import You
from youdotcom.models import TaskDetail, TaskResponse
from youdotcom.utils import eventstreaming, get_security_from_env, match_response, match_status_codes


_DEFAULT_POLL_INTERVAL_S = 2.0
_DEFAULT_POLL_TIMEOUT_S = 600.0
# How long to wait for the SSE stream to deliver a terminal event before
# closing it and falling back to polling. The stream may not deliver
# terminal events for tasks that complete shortly after the stream opens,
# so this caps the wait before switching to polling.
_STREAM_FALLBACK_TIMEOUT_S = 45.0
_TERMINAL_TASK_STATUSES = frozenset({"completed", "failed", "cancelled"})
# SSE event names that signal successful task completion in stream mode.
# Both "complete" and "completed" are accepted for forward-compatibility.
# "response.done" is the documented event for non-background streaming.
_TERMINAL_STREAM_EVENTS_OK = frozenset({"response.done", "complete", "completed"})
# SSE event names that signal task failure in stream mode.
_TERMINAL_STREAM_EVENTS_ERR = frozenset({"error", "failed", "cancelled"})


@dataclass
class RawStreamEvent:
    """Tolerant SSE event representation.

    Attributes:
        id: SSE event ID (``id:`` directive) when supplied.
        event: Raw event name as received from the server, NOT validated
            against the documented enum.
        data: Parsed JSON payload when the data line is valid JSON,
            otherwise the raw string.
        retry: Optional ``retry:`` directive from the server, if any.
    """

    id: Optional[str]
    event: Optional[str]
    data: Any
    retry: Optional[int]


def _decode_raw_event(raw_json: str) -> RawStreamEvent:
    """Tolerant SSE decoder used by ``stream_research_events_raw``.

    Accepts any JSON object regardless of whether ``event`` matches the
    documented enum, so unknown workflow events pass through instead of
    failing pydantic validation.
    """
    parsed = json.loads(raw_json)
    if not isinstance(parsed, dict):
        return RawStreamEvent(id=None, event=None, data=parsed, retry=None)
    return RawStreamEvent(
        id=parsed.get("id"),
        event=parsed.get("event"),
        data=parsed.get("data"),
        retry=parsed.get("retry"),
    )


def research_background(client: You, **kwargs: Any) -> TaskResponse:
    """Submit a research task with ``background=True`` and return ``TaskResponse``.

    Equivalent to ``client.research(..., background=True)`` but asserts the
    response is a ``TaskResponse`` so callers get a strong return type
    without needing to narrow ``Union[ResearchResponse, TaskResponse]``.
    """
    kw = dict(kwargs)
    kw["background"] = True
    res = client.research(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background requires background=True so the server "
            "returns TaskResponse; got " + type(res).__name__
        )
    return res


async def research_background_async(client: You, **kwargs: Any) -> TaskResponse:
    """Async variant of :func:`research_background`."""
    kw = dict(kwargs)
    kw["background"] = True
    res = await client.research_async(**kw)
    if not isinstance(res, TaskResponse):
        raise TypeError(
            "research_background_async requires background=True so the "
            "server returns TaskResponse; got " + type(res).__name__
        )
    return res


def _poll_detail(
    client: You,
    *,
    task_id: str,
    interval_s: float,
    timeout_s: float,
    deadline: float,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
    http_headers: Optional[Mapping[str, str]] = None,
) -> TaskDetail:
    while True:
        detail = client.get_research_task(
            task_id=task_id,
            server_url=server_url,
            timeout_ms=timeout_ms,
            http_headers=http_headers,
        )
        status = detail.status.value
        if status in _TERMINAL_TASK_STATUSES:
            if status != "completed":
                raise RuntimeError(
                    f"research task {task_id} ended in non-completed state: {status}"
                )
            return detail
        if time.monotonic() >= deadline:
            raise TimeoutError(
                f"research task {task_id} did not complete within {timeout_s}s"
            )
        time.sleep(interval_s)


def poll_research_task(
    client: You,
    task_id: str,
    *,
    interval_s: float = _DEFAULT_POLL_INTERVAL_S,
    timeout_s: float = _DEFAULT_POLL_TIMEOUT_S,
    server_url: Optional[str] = None,
    timeout_ms: Optional[int] = None,
    http_headers: Optional[Mapping[str, str]] = None,
) -> TaskDetail:
    """Poll ``GET /v1/research/{task_id}`` until ``status == "completed"``.

    Raises ``RuntimeError`` if the task ends in a non-completed terminal state
    (``failed`` / ``cancelled``) and ``TimeoutError`` if ``timeout_s`` elapses
    before completion.
    """
    return _poll_detail(
        client,
        task_id=task_id,
        interval_s=interval_s,
        timeout_s=timeout_s,
        deadline=time.monotonic() + timeout_s,
        server_url=server_url,
        timeout_ms=timeout_ms,
        http_headers=http_headers,
    )


