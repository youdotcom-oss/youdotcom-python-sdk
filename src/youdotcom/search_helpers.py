"""Hand-maintained search helpers targeting ``/v1/agents/search``.

This module is NOT regenerated by Speakeasy. It mirrors the generated
``search_post`` request machinery but POSTs to ``/v1/agents/search`` instead
of ``/v1/search``. The agents-search endpoint is a proxy that:

- **With an API key** → forwards to ``/v1/search`` unrestricted (full features).
- **Without a key** → free tier: IP-rate-limited, ``count`` capped at 1–50,
  ``livecrawl`` not allowed. Returns ``402`` on any limit.

Use this as the default search entrypoint for skills, plugins, and MCP tools.
The generated ``search.unified`` / ``search_post`` remain available for callers
who need the raw ``/v1/search`` endpoint.

Re-apply this file after Speakeasy regen (precedent: ``research_helpers.py``,
``utils/security.py``).
"""

