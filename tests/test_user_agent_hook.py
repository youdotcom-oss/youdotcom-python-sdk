"""Unit tests for YDCUserAgentOverrideHook.

This hook is a hand-maintained addition (not regenerated by Speakeasy).
The CHANGELOG flags it as regen-fragile: future SDK regens will overwrite
the file and the hook MUST be re-applied. These tests ensure a regen
revert is caught by CI, mirroring how tests/test_security_env.py guards
the env-var precedence hand-edit.
"""

import httpx
from unittest.mock import Mock

from youdotcom._hooks.registration import YDCUserAgentOverrideHook
from youdotcom._hooks.types import BeforeRequestContext, HookContext
from youdotcom._version import __user_agent__, __version__


def _make_ctx(user_agent: str, sdk_version: str = __version__) -> BeforeRequestContext:
    """Build a minimal BeforeRequestContext for hook testing."""
    config = Mock()
    config.user_agent = user_agent
    config.sdk_version = sdk_version
    parent = HookContext(
        config=config,
        base_url="http://mock.local",
        operation_id="test",
        oauth2_scopes=None,
        security_source=None,
        tags=None,
        extensions=None,
    )
    return BeforeRequestContext(parent)


class TestYDCUserAgentOverrideHook:
    def test_default_speakeasy_ua_is_overridden(self):
        """When user_agent is the speakeasy default, the hook rewrites it to youdotcom-python-sdk/{version}."""
        hook = YDCUserAgentOverrideHook()
        ctx = _make_ctx(__user_agent__)
        request = httpx.Request("GET", "http://mock.local/test")
        hook.before_request(ctx, request)
        assert request.headers["User-Agent"] == f"youdotcom-python-sdk/{__version__}"

    def test_custom_user_agent_passes_through(self):
        """When user_agent is a custom value (e.g. integration UA), the hook passes it through unchanged."""
        hook = YDCUserAgentOverrideHook()
        custom_ua = "langchain-youdotcom/1.0"
        ctx = _make_ctx(custom_ua)
        request = httpx.Request("GET", "http://mock.local/test")
        hook.before_request(ctx, request)
        assert request.headers["User-Agent"] == custom_ua

    def test_speakeasy_prefix_ua_is_overridden(self):
        """A UA starting with speakeasy-sdk/ (but different from default) is still overridden."""
        hook = YDCUserAgentOverrideHook()
        ctx = _make_ctx("speakeasy-sdk/python 9.9.9 custom")
        request = httpx.Request("GET", "http://mock.local/test")
        hook.before_request(ctx, request)
        assert request.headers["User-Agent"] == f"youdotcom-python-sdk/{__version__}"
